--------------------------------------------------------------------------------
-- CTELL · BACKUP (DDL)
--
-- Las tablas de control del backup: se corre UNA VEZ, antes de db/backup.sql (el
-- paquete compila contra ellas). Es la excepción a "los archivos de db/ no crean
-- tablas", igual que asistente-ddl.sql: estas no son del negocio y nadie más las
-- va a crear. Idempotente: lo que ya existe no se toca.
--
--   CTELL_BACKUP_CONFIG  clave / valor: la casilla, el tamaño de cada parte.
--   CTELL_BACKUP_LOG     una fila por corrida, escrita MIENTRAS corre.
--   CTELL_BACKUP_TAREA   lo que le falta a la corrida en curso: cada tramo sigue
--                        desde acá. Se vacía sola al terminar.
--
-- SON PRIVADAS PARA EL ASISTENTE (ES_PRIVADA en db/asistente.sql): la casilla de
-- destino no es un dato para mostrarle a cualquiera con sesión.
--
-- CUOTA: el esquema tiene 25 MB compartidos (ORA-01536 en todo INSERT si se
-- llenan). Estas tablas ocupan muy poco y el log se purga solo a los 90 días, pero
-- si ya está lleno este script falla al crearlas. Verlo antes con:
--   SELECT ROUND(SUM(BYTES) / 1048576, 1) AS MB FROM USER_SEGMENTS;
--------------------------------------------------------------------------------

SET DEFINE OFF
SET SERVEROUTPUT ON

DECLARE
  FUNCTION existe(p_tabla IN VARCHAR2) RETURN BOOLEAN IS
    l_c PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO l_c FROM USER_TABLES WHERE TABLE_NAME = p_tabla;
    IF l_c > 0 THEN
      DBMS_OUTPUT.PUT_LINE('[SKIP] La tabla ' || p_tabla || ' ya existia.');
    END IF;
    RETURN l_c > 0;
  END existe;
BEGIN
  IF NOT existe('CTELL_BACKUP_CONFIG') THEN
    EXECUTE IMMEDIATE q'~
      CREATE TABLE CTELL_BACKUP_CONFIG (
        CLAVE VARCHAR2(60) NOT NULL,
        VALOR VARCHAR2(400),
        CONSTRAINT PK_CTELL_BACKUP_CONFIG PRIMARY KEY (CLAVE)
      )~';
    EXECUTE IMMEDIATE q'~COMMENT ON TABLE CTELL_BACKUP_CONFIG IS 'Configuracion del backup por correo. Privada: la IA no la puede consultar'~';
    DBMS_OUTPUT.PUT_LINE('[OK]   Tabla CTELL_BACKUP_CONFIG creada.');
  END IF;

  IF NOT existe('CTELL_BACKUP_LOG') THEN
    EXECUTE IMMEDIATE q'~
      CREATE TABLE CTELL_BACKUP_LOG (
        ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
        INICIO       DATE NOT NULL,
        FIN          DATE,
        ESTADO       VARCHAR2(20) NOT NULL,
        ENVIADO      CHAR(1),
        PARTES       NUMBER,
        TABLAS       NUMBER,
        FILAS        NUMBER,
        BYTES_SCRIPT NUMBER,
        BYTES_ZIP    NUMBER,
        ERRORES      NUMBER,
        PASO         VARCHAR2(200),
        PASO_EN      DATE,
        DETALLE      VARCHAR2(4000),
        CONSTRAINT PK_CTELL_BACKUP_LOG PRIMARY KEY (ID)
      )~';
    EXECUTE IMMEDIATE q'~COMMENT ON TABLE CTELL_BACKUP_LOG IS 'Una fila por corrida del backup, hora de Paraguay. Privada'~';
    DBMS_OUTPUT.PUT_LINE('[OK]   Tabla CTELL_BACKUP_LOG creada.');
  END IF;

  -- TIPO lleva un tipo de objeto o, en las tareas ARCHIVO, el nombre de la columna.
  IF NOT existe('CTELL_BACKUP_TAREA') THEN
    EXECUTE IMMEDIATE q'~
      CREATE TABLE CTELL_BACKUP_TAREA (
        CORRIDA    NUMBER NOT NULL,
        ORDEN      NUMBER NOT NULL,
        ETAPA      VARCHAR2(20) NOT NULL,
        SECCION    VARCHAR2(60),
        ACCION     VARCHAR2(20) NOT NULL,
        TIPO       VARCHAR2(130),
        NOMBRE     VARCHAR2(130),
        DESDE_FILA NUMBER DEFAULT 0 NOT NULL,
        CONSTRAINT PK_CTELL_BACKUP_TAREA PRIMARY KEY (CORRIDA, ORDEN)
      )~';
    EXECUTE IMMEDIATE q'~COMMENT ON TABLE CTELL_BACKUP_TAREA IS 'Lo que le falta a la corrida en curso del backup. Privada'~';
    DBMS_OUTPUT.PUT_LINE('[OK]   Tabla CTELL_BACKUP_TAREA creada.');
  END IF;

  -- Dinámico: al compilar este bloque la tabla todavía puede no existir.
  EXECUTE IMMEDIATE q'~
    MERGE INTO CTELL_BACKUP_CONFIG t
    USING (SELECT 'PARTE_MB' AS clave, '20' AS valor FROM DUAL) s
       ON (t.CLAVE = s.clave)
     WHEN NOT MATCHED THEN INSERT (CLAVE, VALOR) VALUES (s.clave, s.valor)~';
  COMMIT;
END;
/

SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME LIKE 'CTELL\_BACKUP\_%' ESCAPE '\'
 ORDER BY OBJECT_NAME;
