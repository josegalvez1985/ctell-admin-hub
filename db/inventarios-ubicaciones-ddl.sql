SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME = 'INVENTARIOS_UBICACIONES';

-- ENABLED y VALID. Un trigger INVALID bloquea todo INSERT de la tabla.
SELECT o.OBJECT_NAME, o.STATUS, t.STATUS AS HABILITADO
  FROM USER_OBJECTS o
  JOIN USER_TRIGGERS t ON t.TRIGGER_NAME = o.OBJECT_NAME
 WHERE o.OBJECT_NAME = 'TRG_INVENTARIOS_UBICACIONES_BIUD';

SELECT NAME, LINE, POSITION, TEXT
  FROM USER_ERRORS
 WHERE NAME = 'TRG_INVENTARIOS_UBICACIONES_BIUD'
 ORDER BY SEQUENCE;

--------------------------------------------------------------------------------
-- Consultas de control
--------------------------------------------------------------------------------

-- Conteos cuya CANTIDAD_FISICA no es la suma de sus lineas. El paquete la
-- recalcula al guardar y al cerrar, asi que una fila aca es una linea tocada a
-- mano en un conteo todavia abierto. Cero filas es lo correcto.
SELECT i.ID_INVENTARIO, i.ESTADO, i.CANTIDAD_FISICA,
       CASE WHEN COUNT(iu.CANTIDAD) = COUNT(*) THEN SUM(iu.CANTIDAD) END AS SUMA_LINEAS
  FROM INVENTARIOS i
  JOIN INVENTARIOS_UBICACIONES iu ON iu.ID_INVENTARIO = i.ID_INVENTARIO
 GROUP BY i.ID_INVENTARIO, i.ESTADO, i.CANTIDAD_FISICA
HAVING DECODE(i.CANTIDAD_FISICA,
              CASE WHEN COUNT(iu.CANTIDAD) = COUNT(*) THEN SUM(iu.CANTIDAD) END, 0, 1) = 1;

-- Conteos ABIERTOS sin ninguna ubicacion: los anteriores a esta tabla. No se
-- pueden cerrar hasta que se les cargue al menos una.
SELECT i.ID_INVENTARIO, i.ID_SUCURSAL, i.ID_ARTICULO, i.CANTIDAD_FISICA
  FROM INVENTARIOS i
 WHERE NVL(UPPER(TRIM(i.ESTADO)), 'ABIERTO') = 'ABIERTO'
   AND NOT EXISTS (SELECT 1 FROM INVENTARIOS_UBICACIONES iu
                    WHERE iu.ID_INVENTARIO = i.ID_INVENTARIO);
