--------------------------------------------------------------------------------
-- CTELL · INVENTARIOS · UBICACIONES (DDL)
--
-- Una tabla y su trigger:
--
--   1. INVENTARIOS_UBICACIONES          En que estantes se conto, y cuanto en cada uno.
--   2. TRG_INVENTARIOS_UBICACIONES_BIUD El candado: un conteo cerrado no cambia sus lineas.
--
-- Como db/asistente-ddl.sql, es DDL y se corre UNA vez. Es idempotente: si la
-- tabla ya existe no la toca, y el trigger es CREATE OR REPLACE.
--
--------------------------------------------------------------------------------
-- QUE ES, Y QUE NO ES
--
-- El conteo se carga POR UBICACION: "7 en A1·E3, 5 en B2·E1". Pero sigue siendo
-- UN conteo por articulo y sucursal, y lo que se aplica al cerrar es el TOTAL.
--
-- NO ES STOCK POR UBICACION. EXISTENCIAS sigue siendo una cantidad por
-- articulo y sucursal: una venta no dice de que estante sale, asi que un numero
-- por estante dejaria de ser cierto con la primera venta. Lo que se guarda aca
-- es lo que se encontro en cada lugar EL DIA DEL CONTEO: es evidencia con
-- fecha, no una existencia.
--
-- POR ESO NO HAY UN CONTEO POR UBICACION. Si cada estante fuera un INVENTARIOS
-- aparte, cada cierre ajustaria por diferencia la cantidad de UN estante contra
-- el TOTAL del sistema: con 7 + 5 = 12 y el sistema en 12, el primer cierre
-- restaria 5 y el segundo 7, sin que faltara nada.
--
--------------------------------------------------------------------------------
-- CANTIDAD_FISICA PASA A SER LA SUMA DE LAS LINEAS
--
-- Y SE SIGUE GUARDANDO en INVENTARIOS, aunque se derive: el trigger del cierre
-- (db/inventarios-triggers-ddl.sql) la lee para calcular el ajuste, y
-- reescribirlo para que sume las lineas es tocar el unico escritor de stock que
-- no pasa por PKG_STOCK. La escribe PKG_INVENTARIOS cada vez que guarda las
-- lineas, y la VUELVE A CALCULAR justo antes de cerrar: aunque alguien haya
-- tocado una linea a mano, lo que se aplica es la suma de lo que hay.
--
-- UNA LINEA SIN CANTIDAD ES "ESE ESTANTE NO SE CONTO TODAVIA", no cero. Con una
-- sola en NULL, el total es NULL —sin contar— y el conteo no se puede cerrar.
-- El cero se carga explicito: un estante en blanco no puede significar a la vez
-- "no lo mire" y "estaba vacio".
--
-- Los conteos anteriores a esta tabla no tienen lineas y conservan su
-- CANTIDAD_FISICA. Se ven igual; lo que no se puede es cerrar uno abierto sin
-- cargarle al menos una ubicacion (lo exige el paquete).
--
--------------------------------------------------------------------------------
-- SIN ON DELETE CASCADE, A PROPOSITO
--
-- El trigger de esta tabla lee INVENTARIOS para saber si el conteo sigue
-- ABIERTO. Con CASCADE, borrar un conteo dispararia ese trigger MIENTRAS
-- INVENTARIOS se esta borrando, y Oracle lo corta con ORA-04091 (tabla
-- mutante). PKG_INVENTARIOS.ELIMINAR borra las lineas primero; un DELETE a mano
-- del conteo con lineas falla por la FK, que es lo correcto.
--
--------------------------------------------------------------------------------
-- ORDEN DE EJECUCION
--
--   1. db/inventarios-triggers-ddl.sql   (si no se corrio)
--   2. ESTE ARCHIVO
--   3. db/inventarios.sql                 sin la tabla, PKG_INVENTARIOS compila
--                                         INVALID y todo /inventarios da 500
--
-- Requiere INVENTARIOS y UBICACIONES.
--------------------------------------------------------------------------------

SET DEFINE OFF
SET SERVEROUTPUT ON

DECLARE
  PROCEDURE ejecutar(p_sql IN VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  END ejecutar;

  FUNCTION existe(p_tabla IN VARCHAR2) RETURN BOOLEAN IS
    l_c PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO l_c FROM USER_TABLES WHERE TABLE_NAME = p_tabla;
    IF l_c > 0 THEN
      DBMS_OUTPUT.PUT_LINE('[SKIP] La tabla ' || p_tabla || ' ya existia.');
    END IF;
    RETURN l_c > 0;
  END existe;
BEGIN
  IF NOT existe('INVENTARIOS_UBICACIONES') THEN
    -- CANTIDAD acepta NULL: es el estante que todavia no se conto. El CHECK es
    -- sobre el valor que venga, no sobre su presencia.
    --
    -- UNIQUE (inventario, ubicacion): el mismo estante dos veces en un conteo
    -- son dos numeros para el mismo lugar, y la suma contaria dos veces.
    ejecutar(q'~
      CREATE TABLE INVENTARIOS_UBICACIONES (
        ID_INVENTARIO_UBICACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
        ID_INVENTARIO           NUMBER        NOT NULL,
        ID_UBICACION            NUMBER        NOT NULL,
        CANTIDAD                NUMBER,
        FECHA_CREACION          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT PK_INVENTARIOS_UBICACIONES PRIMARY KEY (ID_INVENTARIO_UBICACION),
        CONSTRAINT UQ_INVENTARIOS_UBICACIONES UNIQUE (ID_INVENTARIO, ID_UBICACION),
        CONSTRAINT FK_INV_UBIC_INVENTARIO FOREIGN KEY (ID_INVENTARIO)
          REFERENCES INVENTARIOS (ID_INVENTARIO),
        CONSTRAINT FK_INV_UBIC_UBICACION FOREIGN KEY (ID_UBICACION)
          REFERENCES UBICACIONES (ID_UBICACION),
        CONSTRAINT CK_INV_UBIC_CANTIDAD CHECK (CANTIDAD IS NULL OR CANTIDAD >= 0)
      )~');
    -- ID_INVENTARIO ya tiene indice: es la primera columna del UNIQUE. Este es
    -- para la FK a UBICACIONES (borrar un estante no barre la tabla) y para
    -- preguntar "que se conto en este estante".
    ejecutar('CREATE INDEX IX_INV_UBIC_UBICACION ON INVENTARIOS_UBICACIONES (ID_UBICACION)');
    ejecutar(q'~COMMENT ON TABLE INVENTARIOS_UBICACIONES IS 'Lo contado en cada ubicacion dentro de un conteo. INVENTARIOS.CANTIDAD_FISICA es la suma. Evidencia del dia del conteo, NO stock por ubicacion'~');
    ejecutar(q'~COMMENT ON COLUMN INVENTARIOS_UBICACIONES.CANTIDAD IS 'NULL = ese estante todavia no se conto (el conteo no se puede cerrar). El cero va explicito'~');
    DBMS_OUTPUT.PUT_LINE('[OK]   Tabla INVENTARIOS_UBICACIONES creada.');
  END IF;
END;
/

--------------------------------------------------------------------------------
-- TRG_INVENTARIOS_UBICACIONES_BIUD — el candado de las lineas
--
-- TRG_INVENTARIOS_BIUD congela la CABECERA de un conteo cerrado. Sin esto, las
-- lineas se podrian seguir cambiando: la evidencia de donde se encontro cada
-- unidad diria otra cosa que la que se aplico.
--
-- Los codigos son los MISMOS del otro trigger (-20102 y -20106), a proposito:
-- PKG_INVENTARIOS ya los traduce a 409 y 400 en ERROR_DE_NEGOCIO, y un codigo
-- nuevo saldria como un 500 mudo hasta que alguien se acuerde de agregarlo.
--
-- No hay tabla mutante: se lee INVENTARIOS y UBICACIONES, no esta tabla.
--------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER TRG_INVENTARIOS_UBICACIONES_BIUD
  BEFORE INSERT OR UPDATE OR DELETE ON INVENTARIOS_UBICACIONES
  FOR EACH ROW
DECLARE
  l_id_inventario NUMBER;
  l_estado        INVENTARIOS.ESTADO%TYPE;
  l_empresa       INVENTARIOS.ID_EMPRESA%TYPE;
  l_sucursal      INVENTARIOS.ID_SUCURSAL%TYPE;
  l_emp_ubicacion UBICACIONES.ID_EMPRESA%TYPE;
  l_suc_ubicacion UBICACIONES.ID_SUCURSAL%TYPE;
BEGIN
  l_id_inventario := CASE WHEN DELETING THEN :OLD.ID_INVENTARIO ELSE :NEW.ID_INVENTARIO END;

  IF UPDATING AND :NEW.ID_INVENTARIO != :OLD.ID_INVENTARIO THEN
    RAISE_APPLICATION_ERROR(
      -20106,
      'Una linea no se pasa a otro conteo: es lo que se encontro en ESE conteo.');
  END IF;

  SELECT NVL(UPPER(TRIM(ESTADO)), 'ABIERTO'), ID_EMPRESA, ID_SUCURSAL
    INTO l_estado, l_empresa, l_sucursal
    FROM INVENTARIOS
   WHERE ID_INVENTARIO = l_id_inventario;

  IF l_estado != 'ABIERTO' THEN
    RAISE_APPLICATION_ERROR(
      -20102,
      'El inventario ' || l_id_inventario || ' esta ' || l_estado ||
      ' y sus ubicaciones ya no se modifican: son la evidencia de lo que se ' ||
      'conto ese dia. Si el numero cambio, carga un conteo nuevo.');
  END IF;

  IF DELETING THEN
    RETURN;
  END IF;

  -- LA UBICACION TIENE QUE SER DEL MISMO DEPOSITO QUE EL CONTEO. Las dos FK
  -- validan cada una contra su tabla y ninguna mira la sucursal: sin esto se
  -- podria registrar lo contado en Central como encontrado en un estante del
  -- local.
  SELECT ID_EMPRESA, ID_SUCURSAL
    INTO l_emp_ubicacion, l_suc_ubicacion
    FROM UBICACIONES
   WHERE ID_UBICACION = :NEW.ID_UBICACION;

  IF l_emp_ubicacion != l_empresa OR l_suc_ubicacion != l_sucursal THEN
    RAISE_APPLICATION_ERROR(
      -20106,
      'La ubicacion ' || :NEW.ID_UBICACION || ' no es de la sucursal del conteo: ' ||
      'se cuenta lo que hay en ESE deposito.');
  END IF;
EXCEPTION
  -- Conteo o ubicacion inexistentes: que el error lo de la FK, que explica mejor.
  WHEN NO_DATA_FOUND THEN NULL;
END;
/

