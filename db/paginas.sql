--------------------------------------------------------------------------------
-- Borra un módulo ORDS si existe, reintentando ante un interbloqueo.
--
-- Copia del que también define db/usuarios.sql: cada archivo se ejecuta por
-- separado y no puede asumir que el otro ya corrió. `CREATE OR REPLACE` hace
-- que redefinirlo sea inocuo.
--
-- Un `WHEN OTHERS THEN NULL` acá se tragaba el ORA-00060 del interbloqueo: el
-- DELETE fallaba en silencio y el DEFINE_MODULE moría después con ORA-00001
-- por nombre duplicado. El interbloqueo aparece cuando otra sesión tiene
-- tomadas las filas de metadatos de ORDS —el propio ORDS sirviendo peticiones
-- mientras se reejecuta el script—, es transitorio y se reintenta.
--------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BORRAR_MODULO_ORDS (p_modulo IN VARCHAR2) AS
  C_INTENTOS CONSTANT PLS_INTEGER := 3;
  l_existe   PLS_INTEGER;
BEGIN
  FOR i IN 1 .. C_INTENTOS LOOP
    BEGIN
      SELECT COUNT(*)
        INTO l_existe
        FROM USER_ORDS_MODULES
       WHERE NAME = p_modulo;

      IF l_existe = 0 THEN
        RETURN;
      END IF;

      ORDS.DELETE_MODULE(p_module_name => p_modulo);
      COMMIT;
      RETURN;

    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE IN (-60, -4020) AND i < C_INTENTOS THEN
          ROLLBACK;
          DBMS_SESSION.SLEEP(2);
        ELSE
          RAISE;
        END IF;
    END;
  END LOOP;
END BORRAR_MODULO_ORDS;
/

BEGIN
  BORRAR_MODULO_ORDS('modulos');

  ORDS.DEFINE_MODULE(
    p_module_name    => 'modulos',
    p_base_path      => '/modulos/',
    p_items_per_page => 0,
    p_status         => 'PUBLISHED',
    p_comments       => 'Catalogo de modulos (requiere token)'
  );

  ----------------------------------------------------------------------------
  -- GET /modulos/  · catálogo completo, con las páginas de cada módulo
  ----------------------------------------------------------------------------
  ORDS.DEFINE_TEMPLATE(p_module_name => 'modulos', p_pattern => '.');

  ORDS.DEFINE_HANDLER(
    p_module_name => 'modulos',
    p_pattern     => '.',
    p_method      => 'GET',
    p_source_type => ORDS.source_type_plsql,
    p_source      => q'~
DECLARE
  l_sesion NUMBER;
  l_items  CLOB;
BEGIN
  l_sesion := PKG_TOKENS.VALIDAR_TOKEN(REPLACE(:authorization, 'Bearer ', ''));
  IF l_sesion IS NULL THEN
    :status_code := 401;
    :resultado := '{"error":"Sesion invalida o vencida"}';
    RETURN;
  END IF;

  SELECT JSON_ARRAYAGG(
           JSON_OBJECT(
             'id'      VALUE m.ID_MODULO,
             'codigo'  VALUE m.CODIGO,
             'nombre'  VALUE m.NOMBRE,
             'icono'   VALUE m.ICONO,
             'orden'   VALUE m.ORDEN,
             -- 'A'/'I' tal cual la columna, sin traducir a numeros.
             'activo'  VALUE UPPER(TRIM(m.ACTIVO)),
             'paginas' VALUE (
               SELECT JSON_ARRAYAGG(
                        JSON_OBJECT(
                          'id'     VALUE p.ID_PAGINA,
                          'codigo' VALUE p.CODIGO,
                          'nombre' VALUE p.NOMBRE,
                          'ruta'   VALUE p.RUTA,
                          'orden'  VALUE p.ORDEN,
                          'activo' VALUE UPPER(TRIM(p.ACTIVO))
                          RETURNING CLOB
                        ) ORDER BY p.ORDEN, p.NOMBRE RETURNING CLOB
