--------------------------------------------------------------------------------
-- CTELL · MODULOS, PAGINAS Y PERMISOS POR USUARIO
--
-- Script único: paquete PL/SQL + endpoints ORDS. Se ejecuta de una sola vez
-- en la hoja de trabajo SQL de APEX, conectado con el esquema del workspace.
--
-- Contenido:
--   0. DDL de referencia  — comentado, se ejecuta APARTE (ver nota)
--   1. PKG_PERMISOS       — módulos, páginas y asignación por usuario
--   2. ORDS /modulos/     — catálogo de módulos (ABM)
--   3. ORDS /paginas/     — catálogo de páginas (ABM)
--   4. ORDS /permisos/    — qué páginas ve cada usuario
--   5. Datos iniciales    — módulo Ventas y sus páginas
--   6. Verificación
--
-- Base de los endpoints: https://oracleapex.com/ords/ctell/
--
-- MODELO DE PERMISOS · dos niveles
--
--   Ventas (MODULO)              ← agrupa, se ve en el menú lateral
--   ├── Clientes (PAGINA)        ← esto es lo que se permite
--   ├── Límites de crédito
--   ├── Facturación
--   └── Cobranzas
--
-- El permiso va sobre la PÁGINA, nunca sobre el módulo. Un módulo aparece en
-- el menú si el usuario tiene al menos una de sus páginas: así no puede haber
-- un menú que no lleva a ninguna parte, ni una página accesible cuyo módulo
-- esté oculto. Por eso no existe una tabla USUARIO_MODULOS.
--
-- La ausencia de fila en USUARIO_PAGINAS es la negación. No hay columna
-- PUEDE_VER con 1/0: un permiso está o no está. Guardar negaciones explícitas
-- abre la pregunta de cuál gana si existieran ambas.
--
-- USUARIOS.ES_ADMIN corta por lo sano: un admin ve todo sin necesitar filas.
-- Sin eso, un error al asignar permisos dejaría al sistema sin nadie capaz de
-- corregirlo.
--
-- ESTADO: la columna ACTIVO usa 'A' (activo) / 'I' (inactivo), igual que
-- USUARIOS. Ver la nota extensa en db/usuarios.sql: compararla contra un
-- número la rompe con ORA-01722.
--------------------------------------------------------------------------------

