  l_sesion NUMBER;
  l_admin  NUMBER := 0;
  l_items  CLOB;
BEGIN
  l_sesion := PKG_TOKENS.VALIDAR_TOKEN(REPLACE(:authorization, 'Bearer ', ''));
  IF l_sesion IS NULL THEN
    :status_code := 401;
    :resultado := '{"error":"Sesion invalida o vencida"}';
    RETURN;
  END IF;

  IF PKG_PERMISOS.ES_ADMIN(l_sesion) THEN
    l_admin := 1;
  END IF;

  -- El admin ve el catalogo completo; el resto, solo lo asignado. La
  -- condicion l_admin = 1 corta el filtro por USUARIO_PAGINAS.
  SELECT JSON_ARRAYAGG(
           JSON_OBJECT(
             'id'      VALUE m.ID_MODULO,
             'codigo'  VALUE m.CODIGO,
             'nombre'  VALUE m.NOMBRE,
             'icono'   VALUE m.ICONO,
             'orden'   VALUE m.ORDEN,
             'paginas' VALUE (
               SELECT JSON_ARRAYAGG(
                        JSON_OBJECT(
                          'id'     VALUE p.ID_PAGINA,
                          'codigo' VALUE p.CODIGO,
                          'nombre' VALUE p.NOMBRE,
                          'ruta'   VALUE p.RUTA,
                          'orden'  VALUE p.ORDEN
                          RETURNING CLOB
                        ) ORDER BY p.ORDEN, p.NOMBRE RETURNING CLOB
                      )
                 FROM PAGINAS p
                WHERE p.ID_MODULO = m.ID_MODULO
                  AND UPPER(TRIM(p.ACTIVO)) = 'A'
                  AND (l_admin = 1
                       OR EXISTS (SELECT 1
                                    FROM USUARIO_PAGINAS up
                                   WHERE up.ID_PAGINA  = p.ID_PAGINA
                                     AND up.ID_USUARIO = l_sesion))
             ) FORMAT JSON
             RETURNING CLOB
           ) ORDER BY m.ORDEN, m.NOMBRE RETURNING CLOB
         )
    INTO l_items
    FROM MODULOS m
   WHERE UPPER(TRIM(m.ACTIVO)) = 'A'
     -- Un modulo sin paginas visibles no se muestra: seria un menu que no
     -- lleva a ninguna parte.
     AND EXISTS (SELECT 1
                   FROM PAGINAS p
                  WHERE p.ID_MODULO = m.ID_MODULO
                    AND UPPER(TRIM(p.ACTIVO)) = 'A'
                    AND (l_admin = 1
                         OR EXISTS (SELECT 1
                                      FROM USUARIO_PAGINAS up
