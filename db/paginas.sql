CREATE OR REPLACE PACKAGE PKG_PERMISOS AS

  -- Mismo rango de errores de negocio que PKG_USUARIOS: los handlers los
  -- traducen igual a 400/404.
  C_ERR_DUPLICADO CONSTANT PLS_INTEGER := -20001;
  C_ERR_NO_EXISTE CONSTANT PLS_INTEGER := -20002;
  C_ERR_EN_USO    CONSTANT PLS_INTEGER := -20003;
  C_ERR_DATOS     CONSTANT PLS_INTEGER := -20004;

  C_ESTADO_ACTIVO   CONSTANT VARCHAR2(1) := 'A';
  C_ESTADO_INACTIVO CONSTANT VARCHAR2(1) := 'I';

  ------------------------------------------------------------------ MODULOS --

  PROCEDURE CREAR_MODULO (
    p_codigo    IN  VARCHAR2,
    p_nombre    IN  VARCHAR2,
    p_icono     IN  VARCHAR2 DEFAULT NULL,
    p_orden     IN  NUMBER   DEFAULT 0,
    p_id_modulo OUT NUMBER
  );

  PROCEDURE ACTUALIZAR_MODULO (
    p_id_modulo IN NUMBER,
    p_nombre    IN VARCHAR2 DEFAULT NULL,
    p_icono     IN VARCHAR2 DEFAULT NULL,
    p_orden     IN NUMBER   DEFAULT NULL,
    p_activo    IN VARCHAR2 DEFAULT NULL
  );

  PROCEDURE ELIMINAR_MODULO (p_id_modulo IN NUMBER);

  ------------------------------------------------------------------ PAGINAS --

  PROCEDURE CREAR_PAGINA (
    p_id_modulo IN  NUMBER,
    p_codigo    IN  VARCHAR2,
    p_nombre    IN  VARCHAR2,
    p_ruta      IN  VARCHAR2,
    p_orden     IN  NUMBER DEFAULT 0,
    p_id_pagina OUT NUMBER
  );

  PROCEDURE ACTUALIZAR_PAGINA (
    p_id_pagina IN NUMBER,
    p_id_modulo IN NUMBER   DEFAULT NULL,
    p_nombre    IN VARCHAR2 DEFAULT NULL,
    p_ruta      IN VARCHAR2 DEFAULT NULL,
    p_orden     IN NUMBER   DEFAULT NULL,
    p_activo    IN VARCHAR2 DEFAULT NULL
  );

  PROCEDURE ELIMINAR_PAGINA (p_id_pagina IN NUMBER);

  ----------------------------------------------------------------- PERMISOS --

  -- Otorgar es idempotente: repetirlo no duplica ni falla.
  PROCEDURE OTORGAR (p_id_usuario IN NUMBER, p_id_pagina IN NUMBER);
  PROCEDURE REVOCAR (p_id_usuario IN NUMBER, p_id_pagina IN NUMBER);

  -- Reemplaza TODOS los permisos del usuario por la lista recibida (IDs
  -- separados por coma). Es lo que usa la UI al guardar la selección.
  PROCEDURE REEMPLAZAR (p_id_usuario IN NUMBER, p_ids_paginas IN VARCHAR2);

  -- TRUE si el usuario puede entrar. Un admin siempre puede.
  FUNCTION PUEDE_ACCEDER (
    p_id_usuario IN NUMBER,
    p_ruta       IN VARCHAR2
  ) RETURN BOOLEAN;

  FUNCTION ES_ADMIN (p_id_usuario IN NUMBER) RETURN BOOLEAN;

END PKG_PERMISOS;
