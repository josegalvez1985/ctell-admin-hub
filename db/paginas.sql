-- 7. PRUEBA DEL CIRCUITO DE PERMISOS
--
-- Ejercita otorgar, consultar y revocar sin salir de la base. Si esto imprime
-- OK, el problema (si queda alguno) está en ORDS o en el cliente, no en el
-- paquete.
--
-- No deja rastro: todo lo que hace se revierte al final.
--------------------------------------------------------------------------------

DECLARE
  l_id_usuario NUMBER;
  l_id_pagina  NUMBER;
  l_ruta       VARCHAR2(150);
BEGIN
  DBMS_OUTPUT.PUT_LINE('--- Prueba de permisos ---');

  BEGIN
    SELECT ID_USUARIO INTO l_id_usuario FROM USUARIOS WHERE USUARIO = 'admin';
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('FALLA: no existe el usuario admin.');
      RETURN;
  END;

  BEGIN
    SELECT ID_PAGINA, RUTA INTO l_id_pagina, l_ruta
      FROM PAGINAS WHERE CODIGO = 'VENTAS_CLIENTES';
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('FALLA: no se cargo el catalogo de paginas.');
      RETURN;
  END;

  -- 1. El admin entra a todo sin permisos explícitos.
  IF PKG_PERMISOS.PUEDE_ACCEDER(l_id_usuario, l_ruta) THEN
    DBMS_OUTPUT.PUT_LINE('OK 1/4: el admin accede sin filas en USUARIO_PAGINAS.');
  ELSE
    DBMS_OUTPUT.PUT_LINE('FALLA: el admin no accede. Revisa USUARIOS.ES_ADMIN.');
    RETURN;
  END IF;

  -- 2. Otorgar es idempotente.
  PKG_PERMISOS.OTORGAR(l_id_usuario, l_id_pagina);
  PKG_PERMISOS.OTORGAR(l_id_usuario, l_id_pagina);
  DBMS_OUTPUT.PUT_LINE('OK 2/4: otorgar dos veces no duplica ni falla.');

  -- 3. Reemplazar deja exactamente lo indicado.
  PKG_PERMISOS.REEMPLAZAR(l_id_usuario, TO_CHAR(l_id_pagina));
  SELECT COUNT(*) INTO l_id_pagina
    FROM USUARIO_PAGINAS WHERE ID_USUARIO = l_id_usuario;

  IF l_id_pagina = 1 THEN
    DBMS_OUTPUT.PUT_LINE('OK 3/4: REEMPLAZAR dejo exactamente 1 permiso.');
  ELSE
    DBMS_OUTPUT.PUT_LINE('FALLA: quedaron ' || l_id_pagina || ' permisos, se esperaba 1.');
  END IF;

  -- 4. Reemplazar con lista vacía deja al usuario sin nada.
  PKG_PERMISOS.REEMPLAZAR(l_id_usuario, NULL);
  SELECT COUNT(*) INTO l_id_pagina
    FROM USUARIO_PAGINAS WHERE ID_USUARIO = l_id_usuario;

  IF l_id_pagina = 0 THEN
    DBMS_OUTPUT.PUT_LINE('OK 4/4: REEMPLAZAR con lista vacia revoca todo.');
    DBMS_OUTPUT.PUT_LINE('>>> El paquete de permisos funciona. <<<');
  ELSE
    DBMS_OUTPUT.PUT_LINE('FALLA: quedaron ' || l_id_pagina || ' permisos.');
  END IF;

  -- La prueba no debe dejar permisos puestos.
  ROLLBACK;
  DBMS_OUTPUT.PUT_LINE('(Cambios de la prueba revertidos.)');

EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('EXCEPCION: ' || SQLERRM);
    DBMS_OUTPUT.PUT_LINE(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
END;
