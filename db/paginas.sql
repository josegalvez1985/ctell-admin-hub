  --
  -- Devuelve solo los módulos con al menos una página permitida, y dentro de
  -- cada uno solo esas páginas. Es lo que dibuja el menú lateral.
  ----------------------------------------------------------------------------
  ORDS.DEFINE_TEMPLATE(p_module_name => 'permisos', p_pattern => 'mi-menu');

  ORDS.DEFINE_HANDLER(
    p_module_name => 'permisos',
    p_pattern     => 'mi-menu',
    p_method      => 'GET',
    p_source_type => ORDS.source_type_plsql,
    p_source      => q'~
