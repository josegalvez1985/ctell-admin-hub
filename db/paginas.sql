CREATE OR REPLACE PACKAGE BODY PKG_PERMISOS AS

  --------------------------------------------------------------------------
  -- Privados
  --------------------------------------------------------------------------

  -- NOTA · la traducción 1/0 -> 'A'/'I' va como CASE inline en cada UPDATE,
  -- no como función auxiliar. Una función privada de paquete no se puede
  -- invocar desde SQL: hacerlo da PLS-00231 y el cuerpo entero no compila.
  -- Lo mismo vale para los JSON_OBJECT de los handlers, que usan CASE.

  PROCEDURE VALIDAR_RUTA (p_ruta IN VARCHAR2) IS
  BEGIN
    -- La ruta tiene que existir en src/routes/ del frontend. Se valida el
    -- formato, no la existencia: la base no puede saber qué rutas hay.
    IF p_ruta IS NULL OR NOT REGEXP_LIKE(p_ruta, '^/[a-z0-9/_-]*$') THEN
      RAISE_APPLICATION_ERROR(C_ERR_DATOS,
        'La ruta debe empezar con / y usar solo minusculas, numeros, guion y barra');
    END IF;
  END VALIDAR_RUTA;

  --------------------------------------------------------------------------
  -- Modulos
  --------------------------------------------------------------------------

  PROCEDURE CREAR_MODULO (
    p_codigo    IN  VARCHAR2,
    p_nombre    IN  VARCHAR2,
    p_icono     IN  VARCHAR2 DEFAULT NULL,
    p_orden     IN  NUMBER   DEFAULT 0,
    p_id_modulo OUT NUMBER
  ) IS
    l_codigo VARCHAR2(30) := UPPER(TRIM(p_codigo));
  BEGIN
    IF l_codigo IS NULL OR LENGTH(l_codigo) < 2 THEN
      RAISE_APPLICATION_ERROR(C_ERR_DATOS, 'El codigo es obligatorio');
    END IF;

    IF TRIM(p_nombre) IS NULL THEN
      RAISE_APPLICATION_ERROR(C_ERR_DATOS, 'El nombre es obligatorio');
    END IF;

    INSERT INTO MODULOS (CODIGO, NOMBRE, ICONO, ORDEN, ACTIVO)
    VALUES (l_codigo, TRIM(p_nombre), TRIM(p_icono), NVL(p_orden, 0), C_ESTADO_ACTIVO)
    RETURNING ID_MODULO INTO p_id_modulo;

  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      RAISE_APPLICATION_ERROR(C_ERR_DUPLICADO, 'Ya existe un modulo con ese codigo');
  END CREAR_MODULO;

  PROCEDURE ACTUALIZAR_MODULO (
    p_id_modulo IN NUMBER,
    p_nombre    IN VARCHAR2 DEFAULT NULL,
    p_icono     IN VARCHAR2 DEFAULT NULL,
    p_orden     IN NUMBER   DEFAULT NULL,
    p_activo    IN VARCHAR2 DEFAULT NULL
  ) IS
  BEGIN
    -- El CODIGO no se actualiza: es la referencia estable que usa el resto
    -- del sistema. Para cambiarlo, se crea otro módulo.
    UPDATE MODULOS
       SET NOMBRE = NVL(TRIM(p_nombre), NOMBRE),
           ICONO  = NVL(TRIM(p_icono), ICONO),
           ORDEN  = NVL(p_orden, ORDEN),
           -- p_activo ya es el codigo de la columna: 'A' o 'I'. NULL conserva
           -- el valor actual, y un valor invalido tambien: es preferible
           -- ignorarlo a escribir basura en la columna.
           ACTIVO = CASE UPPER(TRIM(p_activo))
                      WHEN C_ESTADO_ACTIVO   THEN C_ESTADO_ACTIVO
                      WHEN C_ESTADO_INACTIVO THEN C_ESTADO_INACTIVO
                      ELSE ACTIVO
                    END
     WHERE ID_MODULO = p_id_modulo;

    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(C_ERR_NO_EXISTE, 'El modulo no existe');
    END IF;
  END ACTUALIZAR_MODULO;

  PROCEDURE ELIMINAR_MODULO (p_id_modulo IN NUMBER) IS
    l_paginas NUMBER;
  BEGIN
    -- La FK ya lo impediría, pero el mensaje de Oracle no explica nada al
    -- usuario. Se chequea antes para devolver algo entendible.
    SELECT COUNT(*) INTO l_paginas FROM PAGINAS WHERE ID_MODULO = p_id_modulo;

    IF l_paginas > 0 THEN
      RAISE_APPLICATION_ERROR(C_ERR_EN_USO,
        'El modulo tiene ' || l_paginas || ' pagina(s): eliminalas primero');
    END IF;

    DELETE FROM MODULOS WHERE ID_MODULO = p_id_modulo;

    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(C_ERR_NO_EXISTE, 'El modulo no existe');
    END IF;
  END ELIMINAR_MODULO;

  --------------------------------------------------------------------------
  -- Paginas
  --------------------------------------------------------------------------

  PROCEDURE CREAR_PAGINA (
    p_id_modulo IN  NUMBER,
    p_codigo    IN  VARCHAR2,
    p_nombre    IN  VARCHAR2,
    p_ruta      IN  VARCHAR2,
    p_orden     IN  NUMBER DEFAULT 0,
    p_id_pagina OUT NUMBER
  ) IS
    l_codigo VARCHAR2(50) := UPPER(TRIM(p_codigo));
    l_existe NUMBER;
  BEGIN
    IF l_codigo IS NULL OR LENGTH(l_codigo) < 2 THEN
      RAISE_APPLICATION_ERROR(C_ERR_DATOS, 'El codigo es obligatorio');
    END IF;

    IF TRIM(p_nombre) IS NULL THEN
      RAISE_APPLICATION_ERROR(C_ERR_DATOS, 'El nombre es obligatorio');
    END IF;

    VALIDAR_RUTA(p_ruta);

    SELECT COUNT(*) INTO l_existe FROM MODULOS WHERE ID_MODULO = p_id_modulo;
    IF l_existe = 0 THEN
      RAISE_APPLICATION_ERROR(C_ERR_NO_EXISTE, 'El modulo no existe');
    END IF;

    INSERT INTO PAGINAS (ID_MODULO, CODIGO, NOMBRE, RUTA, ORDEN, ACTIVO)
    VALUES (p_id_modulo, l_codigo, TRIM(p_nombre), LOWER(TRIM(p_ruta)),
            NVL(p_orden, 0), C_ESTADO_ACTIVO)
    RETURNING ID_PAGINA INTO p_id_pagina;

  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      RAISE_APPLICATION_ERROR(C_ERR_DUPLICADO,
        'Ya existe una pagina con ese codigo o esa ruta');
  END CREAR_PAGINA;

  PROCEDURE ACTUALIZAR_PAGINA (
    p_id_pagina IN NUMBER,
    p_id_modulo IN NUMBER   DEFAULT NULL,
    p_nombre    IN VARCHAR2 DEFAULT NULL,
    p_ruta      IN VARCHAR2 DEFAULT NULL,
    p_orden     IN NUMBER   DEFAULT NULL,
    p_activo    IN VARCHAR2 DEFAULT NULL
  ) IS
  BEGIN
    IF p_ruta IS NOT NULL THEN
      VALIDAR_RUTA(p_ruta);
    END IF;

    UPDATE PAGINAS
       SET ID_MODULO = NVL(p_id_modulo, ID_MODULO),
           NOMBRE    = NVL(TRIM(p_nombre), NOMBRE),
           RUTA      = NVL(LOWER(TRIM(p_ruta)), RUTA),
           ORDEN     = NVL(p_orden, ORDEN),
           -- 'A'/'I'; ver la nota en ACTUALIZAR_MODULO.
           ACTIVO    = CASE UPPER(TRIM(p_activo))
                         WHEN C_ESTADO_ACTIVO   THEN C_ESTADO_ACTIVO
                         WHEN C_ESTADO_INACTIVO THEN C_ESTADO_INACTIVO
                         ELSE ACTIVO
                       END
     WHERE ID_PAGINA = p_id_pagina;

    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(C_ERR_NO_EXISTE, 'La pagina no existe');
    END IF;

  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      RAISE_APPLICATION_ERROR(C_ERR_DUPLICADO, 'Ya existe otra pagina con esa ruta');
  END ACTUALIZAR_PAGINA;

  PROCEDURE ELIMINAR_PAGINA (p_id_pagina IN NUMBER) IS
  BEGIN
    -- Los permisos caen por el ON DELETE CASCADE de USUARIO_PAGINAS.
    DELETE FROM PAGINAS WHERE ID_PAGINA = p_id_pagina;

    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(C_ERR_NO_EXISTE, 'La pagina no existe');
    END IF;
  END ELIMINAR_PAGINA;

  --------------------------------------------------------------------------
  -- Permisos
  --------------------------------------------------------------------------

  PROCEDURE OTORGAR (p_id_usuario IN NUMBER, p_id_pagina IN NUMBER) IS
  BEGIN
    INSERT INTO USUARIO_PAGINAS (ID_USUARIO, ID_PAGINA)
    VALUES (p_id_usuario, p_id_pagina);
  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      -- Ya lo tenía: otorgar dos veces es un no-op, no un error.
      NULL;
  END OTORGAR;

  PROCEDURE REVOCAR (p_id_usuario IN NUMBER, p_id_pagina IN NUMBER) IS
  BEGIN
    DELETE FROM USUARIO_PAGINAS
     WHERE ID_USUARIO = p_id_usuario
       AND ID_PAGINA  = p_id_pagina;
    -- Sin error si no existía: revocar es idempotente.
  END REVOCAR;

  PROCEDURE REEMPLAZAR (p_id_usuario IN NUMBER, p_ids_paginas IN VARCHAR2) IS
    l_existe NUMBER;
  BEGIN
    SELECT COUNT(*) INTO l_existe FROM USUARIOS WHERE ID_USUARIO = p_id_usuario;
    IF l_existe = 0 THEN
      RAISE_APPLICATION_ERROR(C_ERR_NO_EXISTE, 'El usuario no existe');
    END IF;

    -- Borrar e insertar dentro de la misma transacción: si algo falla, el
    -- ROLLBACK del handler deja los permisos como estaban. Nunca queda a
    -- medias con el usuario sin acceso a nada.
    DELETE FROM USUARIO_PAGINAS WHERE ID_USUARIO = p_id_usuario;

    IF p_ids_paginas IS NOT NULL AND TRIM(p_ids_paginas) IS NOT NULL THEN
      INSERT INTO USUARIO_PAGINAS (ID_USUARIO, ID_PAGINA)
      SELECT p_id_usuario, TO_NUMBER(COLUMN_VALUE)
        FROM XMLTABLE(('"' || REPLACE(p_ids_paginas, ',', '","') || '"'))
       WHERE TO_NUMBER(COLUMN_VALUE) IN (SELECT ID_PAGINA FROM PAGINAS);
      -- El IN filtra IDs inexistentes en vez de abortar: la UI podría mandar
      -- una página borrada por otro usuario mientras editaba.
    END IF;
  END REEMPLAZAR;

  FUNCTION ES_ADMIN (p_id_usuario IN NUMBER) RETURN BOOLEAN IS
    l_admin VARCHAR2(1);
  BEGIN
    SELECT UPPER(TRIM(ES_ADMIN)) INTO l_admin
      FROM USUARIOS
     WHERE ID_USUARIO = p_id_usuario;

    RETURN l_admin = 'S';
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RETURN FALSE;
  END ES_ADMIN;

  FUNCTION PUEDE_ACCEDER (
    p_id_usuario IN NUMBER,
    p_ruta       IN VARCHAR2
  ) RETURN BOOLEAN IS
    l_cuenta NUMBER;
  BEGIN
    -- El admin entra a todo sin filas en USUARIO_PAGINAS.
    IF ES_ADMIN(p_id_usuario) THEN
      RETURN TRUE;
    END IF;

    SELECT COUNT(*)
      INTO l_cuenta
      FROM USUARIO_PAGINAS up
      JOIN PAGINAS p ON p.ID_PAGINA = up.ID_PAGINA
      JOIN MODULOS m ON m.ID_MODULO = p.ID_MODULO
     WHERE up.ID_USUARIO = p_id_usuario
       AND p.RUTA = LOWER(TRIM(p_ruta))
       -- Inactivar el módulo corta el acceso a sus páginas sin tener que
       -- revocar permiso por permiso.
       AND UPPER(TRIM(p.ACTIVO)) = C_ESTADO_ACTIVO
       AND UPPER(TRIM(m.ACTIVO)) = C_ESTADO_ACTIVO;

    RETURN l_cuenta > 0;
  END PUEDE_ACCEDER;

END PKG_PERMISOS;
