--------------------------------------------------------------------------------
-- CTELL · ASISTENTE (DDL)
--
-- Las estructuras del asistente con IA: se corre UNA VEZ, antes de
-- db/asistente.sql (el paquete compila contra estas tablas). Es la excepción a
-- "los archivos de db/ no crean tablas", igual que inventarios-triggers-ddl.sql:
-- estas dos tablas no son del negocio sino del asistente, y nadie más las va a
-- crear.
--
-- Idempotente: lo que ya existe no se toca.
--
--   IA_CONFIG       clave / valor: la clave de la API, el modelo, los límites.
--   IA_CONSULTAS    cada pregunta: quién, cuándo, la respuesta, el SQL que
--                   corrió la IA y los tokens. Es también el contador del
--                   límite diario.
--   V_IA_USUARIOS   USUARIOS sin el hash ni la sal, para que la IA pueda decir
--                   "quién cargó esto".
--
-- LAS TRES SON INVISIBLES PARA LA IA SALVO LA VISTA. PKG_ASISTENTE no le
-- describe ni le deja leer las IA_* (en IA_CONFIG está la clave), TOKENS (las
-- sesiones) ni USUARIOS (CONTRASENA_HASH y SALT). Excluir la tabla entera es lo
-- único que funciona: el filtro de consultas mira identificadores, y un
-- `SELECT *` no nombra ninguna columna.
--
-- La vista no expone CORREO ni ES_ADMIN: el ABM de usuarios es sólo para
-- administradores, y el asistente lo usa cualquiera con sesión.
--
-- SI ESTE ESQUEMA YA TIENE OTRO ASISTENTE (ethos, alquiGO), IA_CONFIG e
-- IA_CONSULTAS chocan. El bloque de abajo lo detecta: la de este proyecto
-- guarda ID_USUARIO, la de ethos USUARIO. En ese caso hay que renombrar las de
-- acá (y el patrón de ES_PRIVADA en db/asistente.sql) en vez de compartirlas.
--------------------------------------------------------------------------------

SET DEFINE OFF
SET SERVEROUTPUT ON

DECLARE
  PROCEDURE ejecutar(p_sql IN VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  END ejecutar;

  FUNCTION existe(p_tabla IN VARCHAR2) RETURN BOOLEAN IS
    l_c PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO l_c FROM USER_TABLES WHERE TABLE_NAME = p_tabla;
    IF l_c > 0 THEN
      DBMS_OUTPUT.PUT_LINE('[SKIP] La tabla ' || p_tabla || ' ya existia.');
    END IF;
    RETURN l_c > 0;
  END existe;
BEGIN
  IF NOT existe('IA_CONFIG') THEN
    ejecutar(q'~
      CREATE TABLE IA_CONFIG (
        CLAVE         VARCHAR2(60)   NOT NULL,
        VALOR         VARCHAR2(4000),
        MODIFICADO_EL DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT PK_IA_CONFIG PRIMARY KEY (CLAVE)
      )~');
    ejecutar(q'~COMMENT ON TABLE IA_CONFIG IS 'Configuracion del asistente con IA (clave de la API, modelo, limites). Privada: la IA no la puede consultar'~');
    DBMS_OUTPUT.PUT_LINE('[OK]   Tabla IA_CONFIG creada.');
  END IF;

  -- Sin FK contra USUARIOS a propósito: es un registro, y una FK haría que
  -- borrar un usuario que alguna vez preguntó algo diera 409.
  IF NOT existe('IA_CONSULTAS') THEN
    ejecutar(q'~
      CREATE TABLE IA_CONSULTAS (
        ID                    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
        ID_USUARIO            NUMBER        NOT NULL,
        ID_EMPRESA            NUMBER,
        FECHA                 DATE          NOT NULL,
        PANTALLA              VARCHAR2(200),
        PREGUNTA              CLOB,
        RESPUESTA             CLOB,
        CONSULTAS             CLOB,
        VUELTAS               NUMBER,
        TOKENS_ENTRADA        NUMBER,
        TOKENS_SALIDA         NUMBER,
        TOKENS_CACHE_LEIDOS   NUMBER,
        TOKENS_CACHE_ESCRITOS NUMBER,
        MILISEGUNDOS          NUMBER,
        MODELO                VARCHAR2(60),
        ERROR                 VARCHAR2(4000),
        CONSTRAINT PK_IA_CONSULTAS PRIMARY KEY (ID)
      )~');
    ejecutar('CREATE INDEX IX_IA_CONSULTAS_USR ON IA_CONSULTAS (ID_USUARIO, FECHA)');
    ejecutar(q'~COMMENT ON TABLE IA_CONSULTAS IS 'Cada pregunta al asistente con IA: quien, cuando (hora de Paraguay), la respuesta, las consultas SQL y los tokens. Privada'~');
    ejecutar(q'~COMMENT ON COLUMN IA_CONSULTAS.CONSULTAS IS 'JSON: [{motivo, sql, filas, error}]. Nunca viaja al navegador'~');
    ejecutar(q'~COMMENT ON COLUMN IA_CONSULTAS.ERROR IS 'El detalle tecnico del fallo. Las filas con ERROR no cuentan para el limite diario'~');
    DBMS_OUTPUT.PUT_LINE('[OK]   Tabla IA_CONSULTAS creada.');
  END IF;

  -- Los valores de entrada. Los que ya están no se tocan: para cambiar uno,
  -- UPDATE IA_CONFIG SET VALOR = '...' WHERE CLAVE = '...'; COMMIT;
  --
  -- LIMITE_DIARIO en 30 y no en los 60 de ethos: la clave es la misma y el
  -- tope de gasto de la organización es de los proyectos juntos.
  FOR c IN (SELECT 'MODELO' AS clave, 'claude-haiku-5-5' AS valor FROM DUAL
            UNION ALL SELECT 'ESFUERZO', 'medium' FROM DUAL
            UNION ALL SELECT 'LIMITE_DIARIO', '30' FROM DUAL
            UNION ALL SELECT 'MAX_FILAS', '200' FROM DUAL) LOOP
    EXECUTE IMMEDIATE q'~
      MERGE INTO IA_CONFIG t
      USING (SELECT :1 AS clave, :2 AS valor FROM DUAL) s
         ON (t.CLAVE = s.clave)
       WHEN NOT MATCHED THEN INSERT (CLAVE, VALOR) VALUES (s.clave, s.valor)~'
      USING c.clave, c.valor;
  END LOOP;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('[OK]   IA_CONFIG con sus valores de entrada.');
END;
/

-- La vista se recrea siempre: no guarda datos.
CREATE OR REPLACE VIEW V_IA_USUARIOS AS
  SELECT ID_USUARIO, USUARIO, NOMBRE_APELLIDO, ACTIVO
    FROM USUARIOS;

COMMENT ON TABLE V_IA_USUARIOS IS 'Los usuarios del sistema (sin credenciales). ACTIVO: A activo, I inactivo';

