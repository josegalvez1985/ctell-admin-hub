DECLARE
  l_n PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO l_n FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'IA_CONSULTAS' AND COLUMN_NAME = 'ID_USUARIO';
  IF l_n = 0 THEN
    DBMS_OUTPUT.PUT_LINE('[ERROR] IA_CONSULTAS existe pero no tiene ID_USUARIO: es la de otro');
    DBMS_OUTPUT.PUT_LINE('        proyecto (ver el encabezado). PKG_ASISTENTE no va a compilar.');
  ELSE
    DBMS_OUTPUT.PUT_LINE('[OK]   IA_CONSULTAS es la de este proyecto.');
  END IF;
END;
/

SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('IA_CONFIG', 'IA_CONSULTAS', 'V_IA_USUARIOS')
 ORDER BY OBJECT_NAME;

SELECT CLAVE, CASE WHEN CLAVE = 'API_KEY' THEN '...' || SUBSTR(VALOR, -4) ELSE VALOR END AS VALOR
  FROM IA_CONFIG
 ORDER BY CLAVE;
